// Helpers
ORG.majorName = (m) => (typeof m === 'string' ? m : m.name);
ORG.tracksOf = (faculty, major) => {
  const m = (ORG.faculties[faculty]?.majors || []).find((x) => ORG.majorName(x) === major);
  return m && typeof m === 'object' ? m.tracks : [];
};
// The unit shown on news: the sub-unit when there is one, otherwise the unit
ORG.displayUnit = (p) => p.subUnit || p.unit;
