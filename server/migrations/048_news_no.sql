-- =========================================================================
-- Short story links: /news-<no>-<slug> (pages.mjs). no = a short story number, oldest first;
-- slug = optional English words the PR team types (lower-case a-z, 0-9 and "-"). The story is found by its number,
-- so a changed slug never breaks a shared link (the old slug answers 301 to the new one).
-- =========================================================================
alter table news add column no bigint;
update news n set no = o.rn from (select id, row_number() over (order by published_at, id) rn from news) o where o.id = n.id;
alter table news alter column no set not null;
alter table news alter column no add generated by default as identity;
select setval(pg_get_serial_sequence('news', 'no'), coalesce((select max(no) from news), 0) + 1, false);
alter table news add constraint news_no_key unique (no);

-- The slug only reads well; the number is what is unique
alter table news drop constraint if exists news_slug_key;
update news set slug = null where slug is not null and not (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(slug) <= 60);
alter table news add constraint news_slug_check check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(slug) <= 60);
